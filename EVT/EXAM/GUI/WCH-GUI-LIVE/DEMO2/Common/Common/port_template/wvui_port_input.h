#ifndef WVUI_PORT_INPUT_H
#define WVUI_PORT_INPUT_H

/* ============================================================================
 * 输入端口 —— 把触摸屏或按键接到 WVUI
 * ----------------------------------------------------------------------------
 * 输入端口只有一个回调：读当前触点，填 `{x, y, pressed}`。分工固定：
 *
 *   端口：读硬件、填 `{x, y, pressed}`；坐标过校准矩阵，可能出负值的
 *         在 read_hardware() 里钳到屏内（越界坐标不命中任何控件）。
 *   框架：命中测试、按压序列、长按、点击、拖拽与滑动判定。
 *
 * 端口自己多做一层判定，同一套界面在不同板子上的操作响应就会不一致。
 * 机械触点去抖走触摸 IC 的配置标志或应用的按键处理，本文件不做。
 *
 * 两种设备（触摸屏 / 按键→屏幕点）的样例实现在 .c 文件里。
 * ==========================================================================*/

#include "wvui_input_port.h"

/* 取输入端口句柄，交给 `wvui_driver_bind_input()`。
 * 唯一要改的是实现文件里的 read_hardware()。 */
const wvui_input_port_t *wvui_port_input(void);

#endif /* WVUI_PORT_INPUT_H */
